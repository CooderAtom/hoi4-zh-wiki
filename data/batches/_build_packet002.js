// Replace "<English label>: <value>" with "<Chinese label>：<value>", keeping <value> byte-identical.
function m(keys) {
  return function (src) {
    let out = src;
    for (const k of keys) {
      const needle = EN[k] + ': ';
      if (!src.includes(needle)) throw new Error('modifier label not found: ' + EN[k] + ' | in: ' + src.slice(0, 90));
      out = out.split(needle).join(SEP + ZH[k] + '：');
    }
    return out.split(SEP).join('');
  };
}

