function write(name, trans) {
  const src = JSON.parse(fs.readFileSync(DIR + name, 'utf8'));
  if (src.units.length !== trans.length) {
    throw new Error(name + ': translation count ' + trans.length + ' != source units ' + src.units.length);
  }
  const items = src.units.map((u, i) => ({
    k: u.k,
    zh: typeof trans[i] === 'function' ? trans[i](u.en) : trans[i]
  }));
  const out = name.replace(/\.json$/, '.zh.json');
  fs.writeFileSync(DIR + out, JSON.stringify({ batch: src.batch, items }), 'utf8');
  console.log('wrote ' + out + ' items=' + items.length);
}

