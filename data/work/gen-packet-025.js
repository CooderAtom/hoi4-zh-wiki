function build(n, table) {
  const name = 'batch-' + String(n).padStart(3, '0');
  const src = JSON.parse(fs.readFileSync(path.join(ROOT, name + '.json'), 'utf8'));
  const items = src.units.map((u) => {
    const zh = table[u.k];
    if (typeof zh !== 'string') throw new Error('missing translation for ' + u.k + ' in batch ' + n);
    return { k: u.k, zh };
  });
  fs.writeFileSync(path.join(ROOT, name + '.zh.json'), JSON.stringify({ batch: n, items }, null, 1) + '\n', 'utf8');
  console.log('wrote ' + name + '.zh.json items=' + items.length + ' (source units=' + src.units.length + ')');
}

