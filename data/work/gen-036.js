const PH = /⟦\d+⟧/g;
function phSeq(s) { const m = s.match(PH); return m ? m : []; }

const reports = [];
for (const [n, table] of [[140, t140], [141, t141]]) {
  const src = JSON.parse(fs.readFileSync(BASE + 'batch-' + n + '.json', 'utf8'));
  const items = [];
  const problems = [];
  src.units.forEach((u, i) => {
    if (!(u.k in table)) { problems.push('MISSING translation for k=' + u.k + ' (idx ' + i + ')'); return; }
    const zh = table[u.k];
    const a = phSeq(u.en), b = phSeq(zh);
    if (a.length !== b.length || a.some((t, j) => t !== b[j])) {
      problems.push('PLACEHOLDER mismatch k=' + u.k + ' src=[' + a.join(',') + '] zh=[' + b.join(',') + ']');
    }
    items.push({ k: u.k, zh });
  });
  // extra keys in table?
  const srcKeys = new Set(src.units.map(u => u.k));
  for (const k of Object.keys(table)) if (!srcKeys.has(k)) problems.push('EXTRA key in table: ' + k);
  fs.writeFileSync(BASE + 'batch-' + n + '.zh.json', JSON.stringify({ batch: n, items }, null, 1) + '\n', 'utf8');
  const dupK = items.length !== new Set(items.map(i => i.k)).size;
  reports.push({ batch: n, srcUnits: src.units.length, outItems: items.length, dupK, problems });
}
